// Read-only virtual-source semantic check against current built public declarations.
const fs=require('node:fs');
const path=require('node:path');
const {createRequire}=require('node:module');
const root=path.resolve(__dirname,'../../../../..');
const ts=createRequire(path.join(root,'packages/ui/package.json'))('typescript');
const targets=['apps/docs/native-fixtures/scenarios/experimental/DateRangeSelector/DateRangeSelector.fixture.tsx','packages/ui/tests/browser/calendar-period-draft-isolation.spec.ts'];
const overlay=new Map(targets.map(p=>[path.join(root,p),fs.readFileSync(path.join(__dirname,'proposed-files',p),'utf8')]));
const configPath=path.join(root,'packages/ui/tests/browser/tsconfig.json');
const config=ts.readConfigFile(configPath,ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,path.dirname(configPath));
const options={...parsed.options,noEmit:true,skipLibCheck:true,typeRoots:[path.join(root,'packages/ui/node_modules/@types')]};
const host=ts.createCompilerHost(options),originalExists=host.fileExists.bind(host),originalRead=host.readFile.bind(host);
host.fileExists=file=>overlay.has(path.resolve(file))||originalExists(file);
host.readFile=file=>overlay.get(path.resolve(file))??originalRead(file);
host.getSourceFile=(file,language)=>{const text=host.readFile(file);return text===undefined?undefined:ts.createSourceFile(file,text,language,true);};
const program=ts.createProgram([...overlay.keys()],options,host);
const diagnostics=ts.getPreEmitDiagnostics(program);
if(diagnostics.length)process.stdout.write(ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCurrentDirectory:()=>root,getCanonicalFileName:x=>x,getNewLine:()=> '\n'}));
process.stdout.write(JSON.stringify({node:process.version,typescript:ts.version,kind:'virtual-source semantic types',targets,diagnostics:diagnostics.length,behavioralExecution:false},null,2)+'\n');
process.exitCode=diagnostics.length?1:0;
