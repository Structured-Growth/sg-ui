const {createRequire}=require('node:module');
const {resolve}=require('node:path');
const {writeFileSync}=require('node:fs');
const root=resolve(__dirname,'../../../../..');
const req=createRequire(resolve(root,'packages/ui/package.json'));
const ts=req('typescript');
const ui=resolve(root,'packages/ui');
const config=ts.readConfigFile(resolve(ui,'tsconfig.json'),ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,ui);
const roots=['packages/ui/src/css-modules.d.ts','packages/ui/src/experimental/HierarchicalMenu/HierarchicalMenu.tsx','packages/ui/src/experimental/HierarchicalMenu/HierarchicalMenu.test.tsx'];
const options={...parsed.options,noEmit:true,types:[],typeRoots:[resolve(ui,'node_modules/@types')]};
const program=ts.createProgram(roots.map(p=>resolve(root,p)),options);
const errors=ts.getPreEmitDiagnostics(program);
const rendered=ts.formatDiagnosticsWithColorAndContext(errors,{getCurrentDirectory:()=>root,getCanonicalFileName:x=>x,getNewLine:()=> '\n'});
writeFileSync(resolve(__dirname,'hierarchical-types.txt'),rendered || 'Scoped source and three unit cases: zero TypeScript diagnostics. No emit or runtime execution.\n');
console.log(rendered || 'Zero TypeScript diagnostics');
process.exitCode=errors.length?1:0;
