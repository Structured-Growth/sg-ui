import {test,expect} from './fixtures';
import {exampleName} from './example-name';
import {checkSources} from './check-sources';

for(const [slug,name] of [['date-range-selector','DateRangeSelector'],['date-range-picker','DateRangePicker']])test(`${name}: independent From/To calendars edit their assigned endpoints`,async({page})=>{
 await page.setViewportSize({width:1440,height:1100});
 await page.goto(`/docs/components/${slug}`);
 const panel=page.getByRole('region',{name:exampleName('Independent From and To months'),exact:true});
 const open=async()=>{if(name==='DateRangePicker')await panel.getByRole('button',{name:'Choose Travel interval',exact:true}).click();};
 await open();
 const calendar=name==='DateRangePicker'?page.getByRole('dialog'):panel;
 const grids=calendar.getByRole('grid');
 const day=(index:number,month:string,date:number)=>grids.nth(index).getByRole('button',{name:new RegExp(`${month} ${date}, 2026`)});
 await expect(grids).toHaveCount(2);
 await day(0,'October',9).click();
 await expect(calendar.getByRole('textbox',{name:'Start date',exact:true})).toHaveValue('10/09/2026');
 await expect(calendar.getByRole('textbox',{name:'End date',exact:true})).toHaveValue('10/16/2026');
 await day(1,'November',5).click();
 await expect(calendar.getByRole('textbox',{name:'Start date',exact:true})).toHaveValue('10/09/2026');
 await expect(calendar.getByRole('textbox',{name:'End date',exact:true})).toHaveValue('11/05/2026');
 await calendar.getByRole('button',{name:'Previous month',exact:true}).nth(1).click();
 await expect(day(0,'October',9)).toBeVisible();
 await day(1,'October',13).focus();await page.keyboard.press('Enter');
 await expect(calendar.getByRole('textbox',{name:'End date',exact:true})).toHaveValue('10/13/2026');
 await calendar.getByRole('button',{name:'Apply',exact:true}).click();
 await open();
 if(await day(1,'October',5).count()===0)await calendar.getByRole('button',{name:'Previous month',exact:true}).nth(1).click();
 await day(1,'October',5).click();
 await expect(calendar.getByRole('textbox',{name:'Start date',exact:true})).toHaveValue('');
 await expect(calendar.getByRole('textbox',{name:'End date',exact:true})).toHaveValue('10/05/2026');
 await expect(calendar.getByRole('button',{name:'Apply',exact:true})).toBeDisabled();
 await calendar.getByRole('button',{name:'Cancel',exact:true}).click();
 await open();
 await expect(calendar.getByRole('textbox',{name:'Start date',exact:true})).toHaveValue('10/09/2026');
 await expect(calendar.getByRole('textbox',{name:'End date',exact:true})).toHaveValue('10/13/2026');
 if(name==='DateRangePicker')await page.keyboard.press('Escape');
 await panel.getByRole('button',{name:'Show source: Independent From and To months',exact:true}).click();
 const source=(await panel.getByRole('code').textContent())!;
 expect(source).toContain('calendarEndpoints={["start","end"]}');
 expect(checkSources([{slug,source}])).toEqual([]);
});
