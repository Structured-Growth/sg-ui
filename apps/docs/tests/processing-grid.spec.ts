import {openSiteTool,closeSiteTool} from './site-tools';
import {exampleName} from './example-name';
import {test,expect} from './fixtures';
import {checkSources} from './check-sources';

for(const width of [1280,375])test(`DataGrid uses a full-width source-backed example and shared page-size dropdown at ${width}px`,async({page,context})=>{
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.setViewportSize({width,height:1000});
  await page.goto('/docs/components/processing-grid');
  await expect(page.getByRole('heading',{name:exampleName('Prop playground'),exact:true})).toHaveCount(0);
  await expect(page.getByRole('heading',{name:exampleName('Independent pagination and layout'),exact:true})).toHaveCount(0);
  const example=page.getByRole('region',{name:exampleName('Course data grid'),exact:true});
  await expect(page.locator('[data-docs-example]')).toHaveCount(1);
  await expect(page.getByRole('region',{name:'DataGrid at a glance',exact:true})).toBeVisible();
  const grid=example.getByRole('grid',{name:'Courses',exact:true});
  await expect(grid).toBeVisible();
  await openSiteTool(page,'Page documentation');
  await expect(page.getByText('Column sizing: width is the preferred starting size;', {exact:false})).toBeVisible();
  await closeSiteTool(page);
  await expect.poll(()=>grid.evaluate(element=>element.getBoundingClientRect().width-element.parentElement!.clientWidth)).toBeGreaterThanOrEqual(-2);
  if(width===1280)await expect.poll(()=>grid.evaluate(element=>Math.abs(element.getBoundingClientRect().width-element.parentElement!.clientWidth))).toBeLessThanOrEqual(2);
  for(const name of ['Course','Status','Score'])expect((await grid.getByRole('columnheader',{name:new RegExp(name)}).boundingBox())!.width).toBeGreaterThanOrEqual(120);
  await expect(grid.getByRole('row')).toHaveCount(6);
  await example.getByRole('button',{name:'Next page',exact:true}).click();
  await expect(example.getByText('Page 2',{exact:true})).toBeVisible();
  const pageSize=example.getByRole('button',{name:/Rows per page/});
  await pageSize.click();
  const options=page.getByRole('listbox',{name:'Rows per page',exact:true});
  await expect(options).toBeVisible();
  await options.getByRole('option',{name:'25',exact:true}).click();
  await expect(pageSize).toBeFocused();
  await expect(example.getByText('Page 1',{exact:true})).toBeVisible();
  await expect(grid.getByRole('row')).toHaveCount(19);
  await example.getByRole('button',{name:'Show source: Course data grid',exact:true}).click();
  const code=example.getByLabel('Source: Course data grid',{exact:true});
  await expect(code).toContainText('"pageSize":25');
  await example.getByRole('searchbox',{name:'Search',exact:true}).fill('Course 18');
  await expect(grid.getByRole('row')).toHaveCount(2);
  await expect(code).toContainText('"search":"Course 18"');
  const source=(await code.textContent())!;
  expect(checkSources([{slug:'course-data-grid',source}])).toEqual([]);
  await example.getByRole('button',{name:'Copy code: Course data grid',exact:true}).click();
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(source);
  await example.getByRole('searchbox',{name:'Search',exact:true}).fill('');
  await pageSize.click();await page.getByRole('option',{name:'5',exact:true}).click();
  const sourceToggle=example.getByRole('button',{name:'Show source: Course data grid',exact:true});
  await sourceToggle.scrollIntoViewIfNeeded();await sourceToggle.click();
  await grid.scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`/tmp/sgui-course-data-grid-${width}.png`,animations:'disabled'});
});

test('DataGrid retains a fill column after pointer-resizing every data column',async({page})=>{
  await page.setViewportSize({width:1440,height:1100});
  await page.goto('/docs/components/processing-grid');
  const example=page.getByRole('region',{name:exampleName('Course data grid'),exact:true});
  const grid=example.getByRole('grid',{name:'Courses',exact:true});
  await grid.scrollIntoViewIfNeeded();
  const filled=async()=>{await expect.poll(()=>grid.evaluate(element=>Math.abs(element.getBoundingClientRect().width-element.parentElement!.clientWidth))).toBeLessThanOrEqual(2);};
  await filled();
  for(const [name,shrink] of [['Course',80],['Status',45],['Score',30]] as const) {
    const header=grid.getByRole('columnheader',{name:new RegExp(name)});
    const before=(await header.boundingBox())!.width;
    const handle=header.locator('[class*="sgui_resizer_"]');
    const box=(await handle.boundingBox())!;
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
    await page.mouse.down();
    await page.mouse.move(box.x+box.width/2-shrink,box.y+box.height/2,{steps:10});
    await page.mouse.up();
    await expect.poll(async()=>(await header.boundingBox())!.width).toBeLessThan(before-shrink/2);
    await filled();
  }
  await page.setViewportSize({width:1600,height:1100});await filled();
  await page.setViewportSize({width:1360,height:1100});await filled();
  await example.getByRole('button',{name:'Show source: Course data grid',exact:true}).click();
  const code=(await example.getByLabel('Source: Course data grid',{exact:true}).textContent())!;
  const widths=code.match(/"widths":(\{[^}]*\})/);
  expect(widths).not.toBeNull();expect(Object.keys(JSON.parse(widths![1])).length).toBeLessThan(3);
  expect(checkSources([{slug:'course-grid-resized',source:code}])).toEqual([]);
  const sourceToggle=example.getByRole('button',{name:'Show source: Course data grid',exact:true});
  await sourceToggle.scrollIntoViewIfNeeded();await sourceToggle.click();
  await grid.scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/sgui-processing-grid-resized.png',animations:'disabled'});
});
