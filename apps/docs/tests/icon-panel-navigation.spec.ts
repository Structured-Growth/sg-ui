import {test,expect} from '@playwright/test';
import {exampleName} from './example-name';
import {checkSources} from './check-sources';

test('icon rail opens independent sliding panels with keyboard names and retained drafts',async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/docs/components/icon-panel-navigation');
  const example=page.getByRole('region',{name:exampleName('Prop playground'),exact:true});
  const rail=example.getByRole('navigation',{name:'Workspace tools',exact:true});
  await expect(rail.getByRole('button')).toHaveCount(3);
  await expect(example.getByRole('region',{name:'Notes',exact:true})).toHaveCount(0);
  const notes=rail.getByRole('button',{name:'Notes',exact:true});
  await notes.scrollIntoViewIfNeeded();
  await page.mouse.move(0,0);
  await notes.hover();
  await expect(notes).toHaveAttribute('data-hovered','true');
  await expect(page.getByRole('tooltip')).toHaveText('Notes');
  await notes.focus();await page.keyboard.press('Enter');
  await expect(notes).toHaveAttribute('aria-expanded','true');
  await expect(notes.locator('svg')).toHaveCSS('width','16px');
  await expect(notes).not.toHaveCSS('background-color','rgba(0, 0, 0, 0)');
  await expect(example.getByRole('region',{name:'Notes',exact:true})).toBeVisible();
  const draft=example.getByRole('textbox',{name:'Workspace notes'});
  await draft.fill('Keep this draft while switching tools.');
  const reference=page.getByRole('region',{name:exampleName('Left icon rail with sliding panels'),exact:true});
  await expect(reference.getByRole('textbox',{name:'Workspace notes'})).toHaveValue('Review the course outline.');
  await rail.getByRole('button',{name:'Tasks',exact:true}).click();
  await expect(draft).toBeHidden();
  await notes.click();
  await expect(draft).toHaveValue('Keep this draft while switching tools.');
  await draft.focus();await page.keyboard.press('Escape');
  await expect(notes).toBeFocused();
  await expect(notes).toHaveAttribute('aria-expanded','false');
  await notes.click();await example.getByRole('button',{name:'Close panel',exact:true}).click();
  await expect(notes).toBeFocused();
  await rail.getByRole('button',{name:'Calendar',exact:true}).click();
  const scroll=example.locator('[data-sgui-part="icon-navigation-content"]').first();
  await scroll.hover();await page.mouse.wheel(0,240);
  await expect.poll(()=>scroll.evaluate(element=>element.scrollTop)).toBeGreaterThan(0);
  await expect(scroll).toHaveCSS('scrollbar-width','thin');
  const source=await example.locator('code[aria-label="Source: Prop playground"]').textContent();
  expect(source).toContain('Keep this draft while switching tools.');
  const sources=await page.locator('code[aria-label^="Source:"]').allTextContents();
  expect(checkSources(sources.map(source=>({slug:'icon-panel-navigation',source})))).toEqual([]);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect(example.getByRole('region',{name:'Calendar',exact:true})).toHaveCSS('animation-name','none');
  await page.emulateMedia({forcedColors:'active'});
  await expect(rail.getByRole('button',{name:'Calendar',exact:true})).toHaveCSS('outline-style','solid');
});

test('icon rail composes beside a separate main menu and fits a narrow host',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1600,height:1000});
  await page.goto('/docs/components/icon-panel-navigation');
  const example=page.getByRole('region',{name:exampleName('AppShell tools separate from the main menu'),exact:true});
  await example.scrollIntoViewIfNeeded();
  const left=example.getByRole('navigation',{name:'Course routes'});
  const main=example.getByRole('main',{name:'Course workspace'});
  const rail=example.getByRole('navigation',{name:'Workspace tools'});
  const panel=example.getByRole('region',{name:'Calendar',exact:true});
  const boxes=await Promise.all([left,main,panel,rail].map(locator=>locator.boundingBox()));
  for(let index=1;index<boxes.length;index++)expect(boxes[index]!.x).toBeGreaterThanOrEqual(boxes[index-1]!.x+boxes[index-1]!.width-1);
  await example.screenshot({path:'/tmp/sgui-icon-panel-navigation-desktop.png',animations:'disabled'});
  await example.getByRole('button',{name:'Close panel',exact:true}).click();
  await expect(rail).toBeVisible();
  await expect(left).toBeVisible();
  await expect(main).toBeVisible();
  const standalone=page.getByRole('region',{name:exampleName('Right icon rail with sliding panels'),exact:true});
  const root=standalone.locator('[data-sgui-part="icon-panel-navigation"]');
  await root.evaluate(element=>{(element.parentElement as HTMLElement).style.width='260px';});
  expect(await root.evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true);
  expect((await root.boundingBox())!.width).toBeLessThanOrEqual(260);
  await page.setViewportSize({width:375,height:800});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await standalone.screenshot({path:'/tmp/sgui-icon-panel-navigation-narrow.png',animations:'disabled'});
});

test('primary icon sections open separate menus with host-owned page navigation',async({page})=>{
  for(const slug of ['icon-panel-navigation','app-shell'])await test.step(slug,async()=>{
  await page.goto(`/docs/components/${slug}`);
  const example=page.getByRole('region',{name:exampleName('Icon sections with independent page menus'),exact:true});
  const rail=example.getByRole('navigation',{name:'Workspace sections'});
  await example.getByRole('link',{name:'Lessons',exact:true}).click();
  await expect(example.getByRole('main').getByRole('heading',{name:'Lessons',exact:true})).toBeVisible();
  await rail.getByRole('button',{name:'People',exact:true}).click();
  await expect(example.getByRole('navigation',{name:'Course pages'})).toHaveCount(0);
  await example.getByRole('link',{name:'Instructors',exact:true}).click();
  await expect(example.getByRole('main').getByRole('heading',{name:'Instructors',exact:true})).toBeVisible();
  await expect(example.getByRole('link',{name:'Instructors',exact:true})).toHaveAttribute('aria-current','page');
  await expect(page).toHaveURL(new RegExp(`${slug}$`));
  const source=await example.locator('code[aria-label^="Source:"]').textContent();
  expect(source).toContain('/people/instructors');
  expect(checkSources([{slug:'icon-panel-navigation-menus',source:source!}])).toEqual([]);
  const primary=page.getByRole('region',{name:exampleName('AppShell main icon navigation'),exact:true});
  const tools=page.getByRole('region',{name:exampleName('AppShell tools separate from the main menu'),exact:true});
  await primary.getByRole('textbox',{name:'Workspace notes'}).fill('Draft for the left rail only');
  await tools.getByRole('button',{name:'Notes',exact:true}).click();
  await expect(tools.getByRole('textbox',{name:'Workspace notes'})).toHaveValue('Review the course outline.');
  await expect(primary.getByRole('textbox',{name:'Workspace notes'})).toHaveValue('Draft for the left rail only');
  const sources=await page.locator('code[aria-label^="Source:"]').allTextContents();
  expect(checkSources(sources.map(source=>({slug,source})))).toEqual([]);
  });
});
