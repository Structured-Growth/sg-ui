import {test,expect} from '@playwright/test';
import {exampleName} from './example-name';
import {checkSources} from './check-sources';
for(const density of ['compact','comfortable'])test(`month/year heading navigates through shared PeriodPicker at ${density} density`,async({page},info)=>{
 await page.goto('/docs/components/date-picker');
 const title=`Choose a month and year — ${density}`;
 const panel=page.getByRole('region',{name:exampleName(title),exact:true});
 const field=panel.getByRole('textbox',{name:'Appointment',exact:true});
 await panel.getByRole('button',{name:'Choose Appointment',exact:true}).click();
 const calendar=page.getByRole('dialog',{name:'Appointment',exact:true});
 const size=(await calendar.boundingBox())!;
 await calendar.getByRole('button',{name:'Choose month and year, October 2026',exact:true}).click();
 const chooser=page.getByRole('group',{name:'Choose month and year',exact:true});
 await expect(page.getByRole('dialog')).toHaveCount(1);await expect(calendar.getByRole('grid')).toHaveCount(0);
 const periodView=calendar.locator('[data-sgui-part="calendar-period-view"]');expect(await periodView.evaluate(element=>element.scrollHeight<=element.clientHeight+1)).toBe(true);
 expect(Math.abs((await calendar.boundingBox())!.height-size.height)).toBeLessThan(1);expect(Math.abs((await calendar.boundingBox())!.width-size.width)).toBeLessThan(1);
 await expect(chooser.getByRole('button',{name:'December',exact:true})).toBeDisabled();
 await info.attach('inline-period-chooser',{body:await calendar.screenshot({path:`/tmp/sgui-inline-period-${density}.png`}),contentType:'image/png'});
 await chooser.getByRole('button',{name:'November',exact:true}).click();
 await chooser.getByRole('button',{name:'Choose year, 2026',exact:true}).click();
 expect(Math.abs((await calendar.boundingBox())!.height-size.height)).toBeLessThan(1);
 await expect(chooser.getByRole('button',{name:'2020',exact:true})).toHaveCount(0);await expect(chooser.getByRole('button',{name:'2030',exact:true})).toHaveCount(0);
 await chooser.getByRole('button',{name:'2027',exact:true}).click();

 await expect(chooser.getByRole('button',{name:'March',exact:true})).toBeDisabled();
 await chooser.getByRole('button',{name:'February',exact:true}).click();await chooser.getByRole('button',{name:'Apply',exact:true}).click();
 await expect(chooser).toHaveCount(0);await expect(field).toHaveValue('10/14/2026');
 await expect(calendar.getByRole('grid')).toHaveAttribute('aria-label',/February 2027/);
 await calendar.getByRole('button',{name:'Monday, February 15, 2027',exact:true}).click();
 await expect(field).toHaveValue('02/15/2027');
 await panel.getByRole('button',{name:`Show source: ${title}`,exact:true}).click();
 expect(checkSources([{slug:'date-picker',source:(await panel.getByRole('code').textContent())!}])).toEqual([]);
});
test('inline period chooser cancels independently, returns focus, and preserves popup size on narrow viewports',async({page})=>{
 await page.setViewportSize({width:375,height:850});await page.goto('/docs/components/date-picker');
 const panel=page.getByRole('region',{name:exampleName('Choose a month and year — compact'),exact:true});
 const trigger=panel.getByRole('button',{name:'Choose Appointment',exact:true});await trigger.click();
 const calendar=page.getByRole('dialog',{name:'Appointment',exact:true});
 const initialSize=(await calendar.boundingBox())!;
 const heading=calendar.getByRole('button',{name:'Choose month and year, October 2026',exact:true});await heading.click();
 const chooser=page.getByRole('group',{name:'Choose month and year',exact:true});
 await expect(chooser).toBeVisible();await expect(page.getByRole('dialog')).toHaveCount(1);const box=(await calendar.boundingBox())!;expect(Math.abs(box.width-initialSize.width)).toBeLessThan(1);expect(Math.abs(box.height-initialSize.height)).toBeLessThan(1);
 expect(box.x).toBeGreaterThanOrEqual(0);expect(box.x+box.width).toBeLessThanOrEqual(375);
 await chooser.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(heading).toBeFocused();await expect(calendar).toBeVisible();
 await heading.click();await chooser.getByRole('button',{name:'Choose year, 2026',exact:true}).press('Escape');await expect(chooser).toHaveCount(0);await expect(heading).toBeFocused();
 await heading.press('Escape');await expect(calendar).toHaveCount(0);await expect(trigger).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
