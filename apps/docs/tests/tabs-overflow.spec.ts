import {test,expect} from '@playwright/test';
import {checkSources} from './check-sources';
const longName='Accessibility and accommodations with a deliberately very long section name';
for(const hasTouch of [false,true])test(`15 tabs promote hidden selections and preserve focus through resize (touch=${hasTouch})`,async({browser,baseURL})=>{
  const context=await browser.newContext({baseURL,viewport:{width:1280,height:1000},hasTouch});
  const page=await context.newPage();const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/docs/components/tabs');
  const panel=page.getByRole('region',{name:'Tabs: Fifteen tabs with overflow · compact',exact:true});
  const sibling=page.getByRole('region',{name:'Tabs: Fifteen tabs with overflow · comfortable',exact:true});
  const tabs=panel.getByRole('tab');
  const more=panel.getByRole('button',{name:'More tabs',exact:true});
  await expect(more).toBeVisible();
  await expect.poll(()=>tabs.count()).toBeLessThan(15);
  const visibleCount=await tabs.count();
  const siblingSource=await sibling.locator('code').textContent();
  await more.click();
  const menu=page.getByRole('menu',{name:'More tabs',exact:true});
  await expect(menu.getByRole('menuitem')).toHaveCount(15-visibleCount);
  await expect(menu.getByRole('menuitem',{name:'Legacy reports',exact:true})).toBeDisabled();
  await menu.getByRole('menuitem',{name:longName,exact:true}).click();
  const active=panel.getByRole('tab',{name:longName,exact:true});
  await expect(active).toHaveAttribute('aria-selected','true');
  await expect(active).toBeFocused();
  await expect(tabs.last()).toHaveAccessibleName(longName);
  const label=active.locator('span').last();
  await expect(label).toHaveCSS('text-overflow','ellipsis');
  expect(await label.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
  await expect(panel.getByRole('tabpanel')).toHaveAccessibleName(longName);
  await expect(panel.getByRole('tabpanel')).toContainText(longName);
  await expect(sibling.getByRole('tab',{name:'Overview',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(sibling.locator('code')).toHaveText(siblingSource!);
  await expect(panel.locator('code')).toContainText('useState("section-12")');
  await page.setViewportSize({width:375,height:1000});
  await expect(active).toBeVisible();await expect(active).toBeFocused();
  await expect(tabs.last()).toHaveAccessibleName(longName);
  const strip=more.locator('xpath=../..');
  expect(await strip.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await more.focus();await page.keyboard.press('ArrowDown');
  await expect(menu).toBeVisible();await page.keyboard.press('Escape');await expect(more).toBeFocused();
  const scrolling=page.getByRole('region',{name:'Tabs: Fifteen scrolling tabs · compact',exact:true});
  await expect(scrolling.getByRole('tab')).toHaveCount(15);
  await expect(scrolling.getByRole('button',{name:'More tabs',exact:true})).toHaveCount(0);
  const list=scrolling.getByRole('tablist');
  expect(await list.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true);
  await scrolling.getByRole('tab',{name:'Overview',exact:true}).click();
  await page.keyboard.press('End');
  await expect(scrolling.getByRole('tab',{name:'Activity log',exact:true})).toBeFocused();
  expect(await list.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
  const sources=await panel.locator('code').allTextContents();
  expect(checkSources(sources.map(source=>({slug:'tabs-overflow',source})))).toEqual([]);
  await page.screenshot({path:`/tmp/sgui-tabs-overflow-${hasTouch}.png`});
  expect(errors).toEqual([]);
  await context.close();
});

test('secondary tabs remain in the menu with spare room and restore their priority after leaving',async({page})=>{
  await page.goto('/docs/components/tabs');
  const panel=page.getByRole('region',{name:'Tabs: Secondary tabs in the menu · compact',exact:true});
  const tabs=panel.getByRole('tab');const more=panel.getByRole('button',{name:'More tabs',exact:true});
  await expect(tabs).toHaveText(['Overview','Lessons']);
  await more.focus();await page.keyboard.press('ArrowDown');
  const menu=page.getByRole('menu',{name:'More tabs',exact:true});
  await expect(menu.getByRole('menuitem')).toHaveText(['Activity log','Advanced settings']);
  await page.keyboard.press('Enter');
  await expect(panel.getByRole('tab',{name:'Activity log',exact:true})).toBeFocused();
  await expect(tabs).toHaveText(['Overview','Lessons','Activity log']);
  await more.click();await expect(menu.getByRole('menuitem')).toHaveText(['Advanced settings']);
  await page.keyboard.press('Escape');
  await panel.getByRole('tab',{name:'Overview',exact:true}).click();
  await expect(tabs).toHaveText(['Overview','Lessons']);
  await more.click();await expect(menu.getByRole('menuitem')).toHaveText(['Activity log','Advanced settings']);
  await page.keyboard.press('Escape');
  const playground=page.getByRole('region',{name:'Prop playground',exact:true});
  await playground.getByRole('button',{name:/overflow/}).filter({hasText:'scroll'}).click();
  await page.getByRole('option',{name:'menu',exact:true}).click();
  await expect(playground.locator('code')).toContainText('overflow={"menu"}');
  await expect(playground.locator('[data-docs-preview]').getByRole('button',{name:'More tabs',exact:true})).toHaveCount(0);
  expect(checkSources((await panel.locator('code').allTextContents()).map(source=>({slug:'secondary-tabs',source})))).toEqual([]);
});
