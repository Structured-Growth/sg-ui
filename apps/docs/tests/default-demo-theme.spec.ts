import {openSiteTool} from './site-tools';
import {exampleName} from './example-name';
import {test,expect} from './fixtures';
import {defaultThemeTokens} from '@structured-growth/sg-ui/tokens';
const rgb=(hex:string)=>`rgb(${hex.slice(1).match(/../g)!.map(part=>parseInt(part,16)).join(', ')})`;

test('None shows global defaults independently of the website and preserves defaults in portals',async({page})=>{
  await page.emulateMedia({colorScheme:'light',contrast:'no-preference',forcedColors:'none'});
  await page.goto('/docs/components/button');
  await openSiteTool(page,'Demo settings');await page.getByRole('button',{name:/Demo theme/}).click();
  await page.getByRole('option',{name:'None — global defaults',exact:true}).click();
  const example=page.getByRole('region',{name:exampleName('Compact density'),exact:true});
  const preview=example.locator('[data-docs-preview]');
  await expect(preview).toHaveAttribute('data-demo-identity','none');
  const observed=await preview.evaluate(element=>Object.fromEntries(Array.from(element.style).filter(key=>key.startsWith('--sgui-')).map(key=>[key,getComputedStyle(element).getPropertyValue(key).trim()])));
  for(const [key,value] of Object.entries(defaultThemeTokens.light))expect(observed[key],key).toBe(String(value));
  const action=preview.getByRole('button',{name:'Example action',exact:true});
  await expect(action).toHaveCSS('background-color',rgb(defaultThemeTokens.light['--sgui-action']));
  await expect(action).toHaveCSS('border-radius',`${parseFloat(defaultThemeTokens.light['--sgui-control-radius'])*16}px`);
  await expect(preview).toHaveAttribute('data-sgui-density','compact');
  expect(await preview.evaluate(element=>getComputedStyle(element).getPropertyValue('--sgui-control-height').trim())).toBe('2rem');
  expect(await page.locator('header').filter({hasText:'Component documentation'}).evaluate(element=>getComputedStyle(element).getPropertyValue('--sgui-action').trim())).toBe('#0b233e');
  await example.screenshot({path:'/tmp/sgui-global-defaults-demo.png',animations:'disabled'});
  await openSiteTool(page,'Demo settings');await page.getByRole('button',{name:/Demo appearance/}).click();await page.getByRole('option',{name:'Dark',exact:true}).click();
  await expect(action).toHaveCSS('background-color',rgb(defaultThemeTokens.dark['--sgui-action']));
  await openSiteTool(page,'Demo settings');await page.getByRole('button',{name:/Demo contrast/}).click();await page.getByRole('option',{name:'Standard',exact:true}).click();
  const nav=page.getByRole('navigation',{name:'Documentation',exact:true});
  await nav.getByRole('button',{name:'Back to Components',exact:true}).click();
  await nav.getByRole('button',{name:'Dialogs & overlays',exact:true}).click();
  await nav.getByRole('link',{name:'AppModal',exact:true}).click();
  await expect(page.getByRole('button',{name:/Demo theme/})).toHaveText('None — global defaults');
  await page.getByRole('region',{name:'Prop playground',exact:true}).getByRole('button',{name:'Open example dialog',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Course settings',exact:true});
  await expect(dialog.getByRole('button',{name:'Save settings',exact:true})).toHaveCSS('background-color',rgb(defaultThemeTokens.dark['--sgui-action']));
  const scope=dialog.locator('xpath=ancestor::*[@data-sgui-scope][1]');
  expect(await scope.evaluate(element=>getComputedStyle(element).getPropertyValue('--sgui-validation-warning').trim())).toBe(defaultThemeTokens.dark['--sgui-validation-warning']);
  await page.keyboard.press('Escape');
  await page.emulateMedia({forcedColors:'active'});
  await expect(page.locator('[data-docs-preview]').first()).toHaveAttribute('data-demo-forced-colors','true');
  expect(await page.locator('[data-docs-preview]').first().evaluate(element=>getComputedStyle(element).getPropertyValue('--sgui-surface').trim())).toBe('Canvas');
});
